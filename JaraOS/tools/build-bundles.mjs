function normalizeModuleId(fromId, request) {
    return path.posix.normalize(path.posix.join(path.posix.dirname(fromId), request));
}

function transformModule(id) {
    const filename = path.join(sourceRoot, ...id.split("/"));
    let source = fs.readFileSync(filename, "utf8");
    const exported = new Set();

    for (const match of source.matchAll(/export\s+(?:const|class|function)\s+([A-Za-z_$][\w$]*)/g)) {
        exported.add(match[1]);
    }
    for (const match of source.matchAll(/export\s*\{([^}]+)\}\s*;/g)) {
        match[1].split(",").map(name => name.trim()).filter(Boolean).forEach(name => exported.add(name));
    }

    source = source.replace(
        /import\s+\{([^}]+)\}\s+from\s+"([^"]+)"\s*;/g,
        (_match, names, request) => "const { " + names.trim() + " } = __modules[\"" + normalizeModuleId(id, request) + "\"];"
    );
    source = source.replace(/export\s+(?=(?:const|class|function)\s+)/g, "");
    source = source.replace(/export\s*\{[^}]+\}\s*;/g, "");

    const returnStatement = exported.size ? "return { " + [...exported].join(", ") + " };" : "return {};";
    return "\n// ---- " + id + " ----\n__modules[\"" + id + "\"] = (() => {\n" + source + "\n" + returnStatement + "\n})();\n";
}

function build(moduleIds, outputName) {
    const banner = "/* JaraOS 3.0 browser bundle. Generated by tools/build-bundles.mjs; edit js/ sources. */\n" +
        "(() => {\n\"use strict\";\nconst __modules = Object.create(null);\n";
    const body = moduleIds.map(transformModule).join("");
    fs.writeFileSync(path.join(projectRoot, "dist", outputName), banner + body + "\n})();\n", "utf8");
}

build(mainModules, "jaraos.js");
build(["services/storage.js", "apps/store.js"], "store.js");

console.log("Built dist/jaraos.js and dist/store.js");
